import { expect, test } from '@playwright/test';

test('admin creates and student completes a strict mock against local Go and PostgreSQL', async ({page,browser}) => {
  test.skip(process.env.EXAM_LIVE !== '1', 'requires isolated local Go and PostgreSQL fixture');
  test.setTimeout(240_000);
  page.setDefaultTimeout(30_000);
  const admin=await browser.newContext({baseURL:`http://127.0.0.1:${process.env.E2E_WEB_PORT || '4173'}`});
  try {
    const adminLogin=await admin.request.post('/api/v1/auth/login',{data:{email:process.env.EXAM_ADMIN_EMAIL,password:process.env.EXAM_PASSWORD}});
    expect(adminLogin.status()).toBe(200);
    const editor=await admin.newPage(); editor.setDefaultTimeout(30_000);
    await editor.goto('/admin-dashboard/assessments',{waitUntil:'domcontentloaded'});
    await editor.getByRole('button',{name:'اختبار جديد'}).click();
    await editor.getByPlaceholder('مثال: EXAM-TAH-PHYS-01 أو MOCK-QUD-01').fill(`BROWSER-${Date.now()}`);
    await editor.getByPlaceholder('مثال: الاختبار المحاكي الشامل للقدرات العامة — النموذج التجريبي 1').fill('محاكي من واجهة الإدارة');
    await editor.getByLabel('مسار الاختبار').selectOption(process.env.EXAM_PATH_ID!);
    await editor.getByRole('button',{name:'محاكي قياس رسمي (أقسام ومؤقت)'}).click();
    await editor.getByLabel('تصنيف المحاكي').selectOption('specialized');
    const saved=editor.waitForResponse(response=>response.url().endsWith('/api/v1/assessments')&&response.request().method()==='POST');
    await editor.getByRole('button',{name:'حفظ الاختبار',exact:true}).click();
    const savedResponse=await saved; expect(savedResponse.status()).toBe(201);
    const savedBody=await savedResponse.json();
    expect(savedBody.assessment.version).toMatchObject({pathId:process.env.EXAM_PATH_ID,subjectId:'',kind:'mock',mockCategory:'specialized'});
    const reloaded=await admin.request.get(`/api/v1/assessments/${savedBody.assessment.id}`);
    expect(reloaded.status()).toBe(200);
    expect((await reloaded.json()).assessment.version.mockCategory).toBe('specialized');
  } finally { await admin.close(); }
  const login=await page.request.post('/api/v1/auth/login',{data:{email:process.env.EXAM_STUDENT_EMAIL,password:process.env.EXAM_PASSWORD}});
  expect(login.status()).toBe(200);
  await page.goto(`/category/${process.env.EXAM_PATH_ID}?tab=mock-exams`,{waitUntil:'domcontentloaded'});
  const lockedMock=page.getByText('محاكي مدفوع للتجربة',{exact:true}).locator('xpath=ancestor::div[contains(@class,"rounded-2xl")][1]');
  await expect(lockedMock.getByRole('link',{name:'عرض الباقة'})).toBeVisible({timeout:30000});
  await expect(lockedMock.getByText('ضمن باقة')).toBeVisible();
  const freeMock=page.getByText('محاكي مقسم',{exact:true}).locator('xpath=ancestor::div[contains(@class,"rounded-2xl")][1]');
  await expect(freeMock.getByRole('button',{name:'ابدأ الاختبار'})).toBeVisible();
  await lockedMock.scrollIntoViewIfNeeded();
  await page.screenshot({path:'test-results/mock-access-live.png'});
  await page.goto(`/assessments/${process.env.EXAM_ASSESSMENT_ID}/start`,{waitUntil:'domcontentloaded'});
  await expect(page.getByText('الأول',{exact:true})).toBeVisible();
  await expect(page.getByText('question 0',{exact:true})).toBeVisible();
  await expect(page.getByText('question 1',{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:/answer/}).click();
  await page.getByRole('button',{name:'إنهاء القسم والانتقال'}).click();
  await page.getByRole('button',{name:'تأكيد الانتقال'}).click();
  await expect(page.getByText('الثاني',{exact:true})).toBeVisible();
  await expect(page.getByText('question 1',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:/answer/}).click();
  await page.getByRole('button',{name:'إنهاء القسم والانتقال'}).click();
  await page.getByRole('button',{name:'تأكيد الانتقال'}).click();
  await expect(page.getByRole('heading',{name:'تم تسليم الاختبار'})).toBeVisible();
  await expect(page.getByText('100.0%')).toBeVisible();
  await page.screenshot({path:'test-results/assessment-live-result.png'});
  await page.getByRole('link',{name:'عرض النتيجة والمراجعة'}).click();
  const cards = page.locator('article').filter({has:page.getByText(/question [01]/)});
  await expect(cards).toHaveCount(2);
  await expect(cards.nth(0)).toContainText('question 0');
  await expect(cards.nth(1)).toContainText('question 1');
  await page.goto(`/assessments/${process.env.EXAM_TIMED_ASSESSMENT_ID}/start`,{waitUntil:'domcontentloaded'});
  await expect(page.getByRole('heading',{name:'تم تسليم الاختبار'})).toBeVisible({timeout:30000});
  await expect(page.getByText('0.0%')).toBeVisible();
});
