import { expect, test } from '@playwright/test';

test('طالب يختبر ويحفظ ويسلم ويراجع بقاعدة بيانات محلية', async ({ page }) => {
  test.skip(process.env.SELF_QUIZ_LIVE !== '1', 'requires isolated Go and PostgreSQL fixture');
  test.setTimeout(600_000);
  page.setDefaultTimeout(60_000);
  page.setDefaultNavigationTimeout(120_000);
  const login = await page.request.post('/api/v1/auth/login', { data: { email: process.env.SELF_QUIZ_EMAIL, password: process.env.SELF_QUIZ_PASSWORD } });
  expect(login.status()).toBe(200);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/quiz?mode=self&pathId=00000000-0000-0000-0000-000000000003&subjectId=00000000-0000-0000-0000-000000000004&sectionId=00000000-0000-0000-0000-000000009001&skillIds=00000000-0000-0000-0000-000000000010&evidenceType=remediation&questionCount=5', { waitUntil: 'domcontentloaded' });
  await expect(page.getByText('القسم: first section')).toBeVisible({ timeout: 60_000 });
  await expect(page.getByText('first skill')).toBeVisible({ timeout: 60_000 });
  await expect(page.getByRole('button', { name: 'ابدأ الاختبار الذاتي الآن' })).toBeEnabled();
  await page.screenshot({ path: 'test-results/self-quiz-live-start.png', fullPage: true });
  await page.getByRole('button', { name: 'ابدأ الاختبار الذاتي الآن' }).click();
  await expect(page.getByText('first', { exact: true })).toBeVisible();
  const attemptId = new URL(page.url()).pathname.split('/').pop();
  await page.getByRole('button', { name: 'مراجعة لاحقاً' }).click();
  await expect(page.getByRole('button', { name: 'معلّم للمراجعة' })).toBeVisible();
  await page.evaluate(() => localStorage.clear());
  await page.goto('/quiz?mode=self', { waitUntil: 'domcontentloaded' });
  await expect(page.getByRole('link', { name: 'استعادة التقدم' })).toBeVisible({ timeout: 30000 });
  await page.getByRole('link', { name: 'استعادة التقدم' }).click();
  await expect(page.getByRole('button', { name: 'معلّم للمراجعة' })).toBeVisible();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await expect(page.getByRole('button', { name: 'معلّم للمراجعة' })).toBeVisible();
  await page.bringToFront();
  await page.waitForTimeout(2200);
  await page.getByRole('button', { name: /yes/ }).click();
  await page.getByRole('button', { name: 'إنهاء الاختبار' }).click();
  await page.getByRole('button', { name: 'نعم، قم بالتسليم' }).click();
  await expect(page.getByRole('heading', { name: 'تم تسليم الاختبار' })).toBeVisible({ timeout: 30000 });
  await expect(page.getByText('100.0%')).toBeVisible();
  const storedResult = await page.request.get(`/api/v1/assessment-attempts/${attemptId}/result`);
  expect(storedResult.status()).toBe(200);
  expect((await storedResult.json()).result.timeSpentSeconds).toBeGreaterThanOrEqual(1);
  await page.reload({ waitUntil: 'domcontentloaded' });
  await expect(page.getByRole('heading', { name: 'تم تسليم الاختبار' })).toBeVisible();
  await page.getByRole('link', { name: 'عرض النتيجة والمراجعة' }).click();
  await expect(page.getByText('first', { exact: true })).toBeVisible();
  await expect(page.getByText('first skill')).toBeVisible();
  await expect(page.getByRole('link', { name: 'اختبار جديد' })).toHaveAttribute('href', '/quiz?mode=self');
  await page.getByRole('button', { name: 'اسأل المساعد النصي 💡' }).click();
  await page.getByRole('button', { name: 'تلميح', exact: true }).click();
  await expect(page.getByText('شرح موثوق احتياطي')).toBeVisible({ timeout: 30000 });
  await page.screenshot({ path: 'test-results/self-quiz-live-result.png', fullPage: true });
});
