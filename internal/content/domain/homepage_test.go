func homepageInput(t *testing.T, raw string) map[string]any {
	t.Helper()
	var input map[string]any
	if err := json.Unmarshal([]byte(raw), &input); err != nil {
		t.Fatal(err)
	}
	return input
}

// Catch coercion, accidental deep merge/default insertion, and loss of false/empty.
func TestHomepagePatchSourceValidation(t *testing.T) {
	input := homepageInput(t, `{"key":"ignored","hero":{"titlePrefix":"","autoRotateImages":false,"rotateIntervalSeconds":3,"unknown":1},"navigation":{"showAutoPaths":false,"items":[{"id":"home","visible":false,"order":0}]},"featuredPathIds":[],"unknown":true}`)
	got, err := ParseHomepagePatch(input)
	if err != nil {
		t.Fatal(err)
	}
	want := homepageInput(t, `{"hero":{"titlePrefix":"","autoRotateImages":false,"rotateIntervalSeconds":3},"navigation":{"showAutoPaths":false,"items":[{"id":"home","visible":false,"order":0}]},"featuredPathIds":[]}`)
	if !reflect.DeepEqual(map[string]any(got), want) {
		t.Fatalf("got %#v want %#v", got, want)
	}
	got, err = ParseHomepagePatch(homepageInput(t, `{"stats":[{"id":"a","label":"طلاب"}],"testimonials":[{"id":"t","name":"اسم","text":"نص"}]}`))
	if err != nil {
		t.Fatal(err)
	}
	stat := got["stats"].([]any)[0].(map[string]any)
	if stat["mode"] != "dynamic" || stat["source"] != "students" {
		t.Fatalf("source defaults: %#v", stat)
	}
	if _, ok := got["hero"]; ok {
		t.Fatal("omitted nested field was inserted into patch")
	}
	if _, ok := stat["manualValue"]; ok {
		t.Fatal("optional source field was defaulted by parser")
	}
}

func TestHomepagePatchRejectsInvalidSourceFields(t *testing.T) {
	for _, raw := range []string{`null`, `{"hero":null}`, `{"stats":null}`, `{"hero":{"autoRotateImages":"false"}}`, `{"hero":{"rotateIntervalSeconds":2}}`, `{"hero":{"rotateIntervalSeconds":61}}`, `{"typography":{"bodyFont":"cairo"}}`, `{"studentExperience":{"visibilityMode":"enrolled"}}`, `{"studentExperience":{"visibilityMode":"other","promptEnrollment":true}}`, `{"navigation":{"items":[{"visible":true}]}}`, `{"stats":[{"id":"","label":"x"}]}`, `{"testimonials":[{"id":"a","name":"x"}]}`, `{"featuredPathIds":[42]}`} {
		if _, err := ParseHomepagePatch(homepageInput(t, raw)); err == nil {
			t.Errorf("accepted %s", raw)
		}
	}
	if _, err := ParseHomepagePatch(map[string]any{"hero": map[string]any{"galleryImages": []any{strings.Repeat("😀", 750001)}}}); err == nil {
		t.Fatal("gallery limit must count UTF-16 code units")
	}
	if _, err := ParseHomepagePatch(map[string]any{"hero": map[string]any{"galleryImages": make([]any, 11)}}); err == nil {
		t.Fatal("more than ten gallery images accepted")
	}
}

func TestHomepageDefaultIsolation(t *testing.T) {
	first := DefaultHomepageSettings()
	if first["key"] != "default" || first["hero"].(map[string]any)["titleHighlight"] != "المئة" {
		t.Fatalf("bad source defaults: %#v", first)
	}
	first["brand"].(map[string]any)["logoText"] = "changed"
	if DefaultHomepageSettings()["brand"].(map[string]any)["logoText"] != "منصة" {
		t.Fatal("request mutated defaults shared with later visitors")
	}
}

// Independently generated by the pinned source Zod schema and Mongoose model,
// not by Go helpers. Catches parser/default drift during the backend migration.
func TestHomepagePinnedSourceCases(t *testing.T) {
	raw, err := os.ReadFile("homepage_source_fixtures.json")
	if err != nil {
		t.Fatal(err)
	}
	var fixtures struct {
		Defaults HomepageSettings
		Cases    []struct {
			Input     map[string]any
			Valid     bool
			Parsed    map[string]any
			Persisted map[string]any
		}
	}
	if err = json.Unmarshal(raw, &fixtures); err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(fixtures.Defaults, DefaultHomepageSettings()) {
		t.Fatal("Go defaults differ from source model defaults")
	}
	for i, tc := range fixtures.Cases {
		got, err := ParseHomepagePatch(tc.Input)
		if (err == nil) != tc.Valid {
			t.Errorf("case %d validity: %v", i, err)
			continue
		}
		if !tc.Valid {
			continue
		}
		if !reflect.DeepEqual(map[string]any(got), tc.Parsed) {
			t.Errorf("case %d parsed: %#v want %#v", i, got, tc.Parsed)
		}
		normalized, err := HomepageSubdocumentDefaults(got)
		if err != nil {
			t.Fatal(err)
		}
		stored := DefaultHomepageSettings()
		for key, value := range normalized {
			stored[key] = value
		}
		if !reflect.DeepEqual(map[string]any(stored), tc.Persisted) {
			t.Errorf("case %d stored: %#v want %#v", i, stored, tc.Persisted)
		}
	}
}
